"""B2: compare fixed-size, semantic and metadata-aware chunking on the knowledge base.

    python -m experiments.chunking_comparison

Embedding model: all-MiniLM-L6-v2 (same as the local vector store), used both
for indexing and, in the semantic chunker, to find topic boundaries. Exact
cosine search, top 5 chunks, document-level relevance from the labelled query
set (src/backend/kb/queries.py). Deterministic (no sampling).

Outputs (results/kb/): b2_chunking_summary.md, b2_chunking_metrics.csv
(per query and method), b2_chunk_stats.csv, b2_paired_bootstrap.csv.
"""

from __future__ import annotations

import itertools
import json
from pathlib import Path

import pandas as pd

from src.backend.evaluation.provenance import environment_info
from src.backend.forecasting.evaluation import paired_day_bootstrap
from src.backend.kb.build import build_documents
from src.backend.kb.chunking import fixed_size_chunks, metadata_chunks, semantic_chunks
from src.backend.kb.queries import build_queries
from src.backend.kb.retrieval_eval import K, CosineIndex, bootstrap_mean_ci, evaluate, minilm_embed

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results" / "kb"
METRICS = ("precision_at_k", "recall_at_k", "mrr", "ndcg_at_k")


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    env = environment_info()
    docs = build_documents()
    queries = build_queries(docs)
    embed = minilm_embed()
    chunk_sets = {
        "fixed_size": fixed_size_chunks(docs),
        "semantic": semantic_chunks(docs, embed),
        "metadata_aware": metadata_chunks(docs),
    }
    stats, per_query = [], []
    for method, chunks in chunk_sets.items():
        lengths = pd.Series([len(c["text"]) for c in chunks])
        stats.append({"method": method, "chunks": len(chunks), "mean_chars": round(lengths.mean(), 1),
                      "median_chars": int(lengths.median()), "max_chars": int(lengths.max())})
        res = evaluate(CosineIndex(chunks, embed), queries, K)
        per_query.append(res.assign(method=method))
        print(f"{method:<15} chunks {len(chunks):4d}  " +
              "  ".join(f"{m} {res[m].mean():.3f}" for m in METRICS))
    per_query = pd.concat(per_query, ignore_index=True)
    per_query.to_csv(OUT / "b2_chunking_metrics.csv", index=False, encoding="utf-8")
    pd.DataFrame(stats).to_csv(OUT / "b2_chunk_stats.csv", index=False, encoding="utf-8")

    boots = []
    for a, b in itertools.combinations(chunk_sets, 2):
        for m in ("ndcg_at_k", "mrr"):
            sa = per_query[per_query.method == a].set_index("query_id")[m]
            sb = per_query[per_query.method == b].set_index("query_id")[m]
            r = paired_day_bootstrap(sa, sb, n_resamples=10_000, seed=0)   # resamples queries (paired)
            boots.append({"method_a": a, "method_b": b, "metric": m, **r.as_dict()})
    boots = pd.DataFrame(boots)
    boots.to_csv(OUT / "b2_paired_bootstrap.csv", index=False, encoding="utf-8")

    L = ["# B2 chunking comparison", "",
         f"Generated by `python -m experiments.chunking_comparison` at base commit {env['git_commit']}.",
         f"{len(docs)} KB documents, {len(queries)} labelled queries, top {K} chunks, all-MiniLM-L6-v2, exact cosine.",
         "Document-level relevance (graded 2/1); definitions in src/backend/kb/retrieval_eval.py.",
         "Values: mean over queries with a 95% bootstrap CI (queries resampled, seed 0).", "",
         "| method | chunks | mean chars | Precision@5 | Recall@5 | MRR | nDCG@5 |", "|---|---|---|---|---|---|---|"]
    for s in stats:
        r = per_query[per_query.method == s["method"]]
        cells = []
        for m in METRICS:
            mean, lo, hi = bootstrap_mean_ci(r[m])
            cells.append(f"{mean:.3f} [{lo:.3f}, {hi:.3f}]")
        L.append(f"| {s['method']} | {s['chunks']} | {s['mean_chars']} | " + " | ".join(cells) + " |")
    L += ["", "## nDCG@5 by query type", "",
          "| query type | n | " + " | ".join(chunk_sets) + " |", "|---|---|" + "---|" * len(chunk_sets)]
    piv = per_query.pivot_table(index="query_type", columns="method", values="ndcg_at_k", aggfunc="mean")
    n = per_query[per_query.method == "fixed_size"].groupby("query_type").size()
    for qt, row in piv.iterrows():
        L.append(f"| {qt} | {n[qt]} | " + " | ".join(f"{row[m]:.3f}" for m in chunk_sets) + " |")
    L += ["", "## Paired bootstrap over queries (A - B; positive = A better for these metrics)", "",
          "| A | B | metric | mean diff | 95% CI | share of resamples with A < B |",
          "|---|---|---|---|---|---|"]
    for _, r in boots.iterrows():
        L.append(f"| {r.method_a} | {r.method_b} | {r.metric} | {r.mean_diff:+.3f} | "
                 f"[{r.ci_low:+.3f}, {r.ci_high:+.3f}] | {r.share_a_better:.3f} |")
    (OUT / "b2_chunking_summary.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    (OUT / "b2_run.json").write_text(json.dumps({"environment": env, "k": K, "queries": len(queries)}, indent=2),
                                     encoding="utf-8")


if __name__ == "__main__":
    main()
