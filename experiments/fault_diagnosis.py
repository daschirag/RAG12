"""B4: fault-diagnosis models on Wind Farm A SCADA (protocol in docs/fault_diagnosis.md).

    python -m experiments.fault_diagnosis

Anomaly detection with leave-one-asset-out evaluation (5 turbines, 22 events)
for logistic regression, random forest and XGBoost (seeds 0-2), plus a
per-dataset Isolation Forest (seeds 0-2). Component attribution for the 12
anomaly events (unsupervised, sensor-group deviation).

Outputs (results/faultdiag/): b4_summary.md, b4_event_predictions.csv,
b4_row_metrics.csv, b4_event_metrics.csv, b4_attribution.csv, b4_run.json.
"""

from __future__ import annotations

import json
import time
from pathlib import Path

import pandas as pd

from src.backend.evaluation.provenance import environment_info
from src.backend.faultdiag.data import load_farm
from src.backend.faultdiag.models import (
    SUPERVISED,
    attribute_components,
    bootstrap_event_metric,
    classification_metrics,
    event_table,
    isolation_forest,
    leave_one_asset_out,
)
from src.backend.kb.taxonomy import categorize, load_events

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results" / "faultdiag"
SEEDS = (0, 1, 2)
MODELS = (*SUPERVISED, "isolation_forest")
METRICS = ("accuracy", "precision", "recall", "f1", "auc")


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    env = environment_info()
    t0 = time.perf_counter()
    events = load_farm("A")
    print(f"loaded {len(events)} datasets in {time.perf_counter() - t0:.0f}s; "
          f"window rows {sum(len(e.y) for e in events)}")

    row_metrics, event_metrics, event_preds = [], [], []
    for model in MODELS:
        for seed in SEEDS:
            rows = (isolation_forest(events, seed) if model == "isolation_forest"
                    else leave_one_asset_out(events, model, seed))
            row_metrics.append({"model": model, "seed": seed, **classification_metrics(rows.y, rows.flag, rows.score)})
            ev = event_table(rows, model)
            event_metrics.append({"model": model, "seed": seed,
                                  **classification_metrics(ev.y, ev.event_flag, ev.event_prob)})
            event_preds.append(ev.assign(model=model, seed=seed))
            print(f"{model:<20} seed {seed}: event AUC {event_metrics[-1]['auc']:.3f} "
                  f"acc {event_metrics[-1]['accuracy']:.3f} | row AUC {row_metrics[-1]['auc']:.3f}")
    row_metrics, event_metrics = pd.DataFrame(row_metrics), pd.DataFrame(event_metrics)
    event_preds = pd.concat(event_preds, ignore_index=True)
    row_metrics.to_csv(OUT / "b4_row_metrics.csv", index=False, encoding="utf-8")
    event_metrics.to_csv(OUT / "b4_event_metrics.csv", index=False, encoding="utf-8")
    event_preds.to_csv(OUT / "b4_event_predictions.csv", index=False, encoding="utf-8")

    # Component attribution for the anomaly events (no model, no labels used).
    info = load_events("A").set_index("event_id")
    attr = []
    for e in events:
        if e.label != "anomaly":
            continue
        ranking = attribute_components(e)
        truth = categorize(info.loc[e.event_id, "event_description"])[0]
        rank = int(list(ranking.index).index(truth)) + 1 if truth in ranking.index else None
        attr.append({"event_id": e.event_id, "asset_id": e.asset_id, "true_component": truth,
                     "predicted_top1": ranking.index[0], "predicted_top2": ranking.index[1],
                     "rank_of_true": rank, "n_components_ranked": len(ranking),
                     "top1_correct": ranking.index[0] == truth, "top2_correct": truth in ranking.index[:2]})
    attr = pd.DataFrame(attr)
    attr.to_csv(OUT / "b4_attribution.csv", index=False, encoding="utf-8")

    def ms(v, d=3):
        v = pd.Series(v, dtype=float)
        return f"{v.mean():.{d}f} +/- {v.std(ddof=1):.{d}f}"

    L = ["# B4 fault diagnosis - Wind Farm A", "",
         f"Generated by `python -m experiments.fault_diagnosis` at base commit {env['git_commit']}.",
         f"{len(events)} event datasets on {len({e.asset_id for e in events})} turbines; "
         f"{sum(e.label == 'anomaly' for e in events)} anomaly / {sum(e.label == 'normal' for e in events)} normal.",
         "Supervised models: leave-one-asset-out. Isolation Forest: fitted per dataset on its own train part.",
         "status_type_id excluded (label leakage). Features: robust z-scores vs the turbine's own train part.",
         "Mean +/- std over seeds 0-2. Event level is primary (22 events); rows within a window are correlated.", "",
         "## Event level (22 events)", "",
         "| model | accuracy | precision | recall | F1 | AUC | AUC 95% CI (seed 0, events resampled) |",
         "|---|---|---|---|---|---|---|"]
    for model in MODELS:
        m = event_metrics[event_metrics.model == model]
        ev0 = event_preds[(event_preds.model == model) & (event_preds.seed == 0)]
        lo, hi = bootstrap_event_metric(ev0, "auc")
        L.append(f"| {model} | " + " | ".join(ms(m[k]) for k in METRICS) + f" | [{lo:.3f}, {hi:.3f}] |")
    L += ["", "## Row level (window rows, every 3rd 10-min row)", "",
          "| model | rows | accuracy | precision | recall | F1 | AUC |", "|---|---|---|---|---|---|---|"]
    for model in MODELS:
        m = row_metrics[row_metrics.model == model]
        L.append(f"| {model} | {int(m.n.iloc[0])} | " + " | ".join(ms(m[k]) for k in METRICS) + " |")
    L += ["", "## Per-event probabilities (seed 0)", "",
          "| event | asset | label | " + " | ".join(MODELS) + " |", "|---|---|---|" + "---|" * len(MODELS)]
    piv = event_preds[event_preds.seed == 0].pivot_table(index=["event_id", "asset_id", "y"], columns="model",
                                                         values="event_prob").reset_index()
    for _, r in piv.sort_values(["y", "asset_id", "event_id"]).iterrows():
        L.append(f"| {int(r.event_id)} | {int(r.asset_id)} | {'anomaly' if r.y else 'normal'} | "
                 + " | ".join(f"{r[m]:.2f}" for m in MODELS) + " |")
    L += ["", "## Component attribution (unsupervised; 12 anomaly events)", "",
          "Classes have 1-6 events each: **these counts are not a trustworthy accuracy estimate.**", "",
          "| event | asset | true component | top-1 | top-2 | rank of true (of ranked) |", "|---|---|---|---|---|---|"]
    for _, r in attr.iterrows():
        L.append(f"| {r.event_id} | {r.asset_id} | {r.true_component} | {r.predicted_top1} | {r.predicted_top2} | "
                 f"{r.rank_of_true} of {r.n_components_ranked} |")
    per_class = attr.groupby("true_component").agg(events=("event_id", "count"), top1=("top1_correct", "sum"),
                                                   top2=("top2_correct", "sum"))
    L += ["", "| true component | events | top-1 correct | top-2 correct |", "|---|---|---|---|"]
    for comp, r in per_class.iterrows():
        L.append(f"| {comp} | {r.events} | {r.top1} | {r.top2} |")
    L.append(f"\nOverall: top-1 {int(attr.top1_correct.sum())}/{len(attr)}, top-2 {int(attr.top2_correct.sum())}/{len(attr)}. "
             f"Chance level for top-1 with {attr.n_components_ranked.iloc[0]} ranked components: "
             f"{1 / attr.n_components_ranked.iloc[0]:.2f}.")
    (OUT / "b4_summary.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    (OUT / "b4_run.json").write_text(json.dumps({"environment": env, "seeds": SEEDS, "models": MODELS}, indent=2),
                                     encoding="utf-8")


if __name__ == "__main__":
    main()
