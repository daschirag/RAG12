"""B4 follow-up: Isolation Forest operating threshold by nested leave-one-asset-out.

    python -m experiments.fault_threshold

Uses the B4 Isolation Forest event scores (results/faultdiag/b4_event_predictions.csv,
event score = fraction of window rows above the turbine's 99th-percentile training
score). For each held-out turbine the event threshold is chosen on the other
turbines' events (maximise F1, ties -> higher threshold) and applied unchanged to
the held-out turbine. Output: results/faultdiag/b4_if_threshold.md and .csv.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from src.backend.evaluation.provenance import environment_info
from src.backend.faultdiag.models import classification_metrics, nested_threshold_eval

OUT = Path(__file__).resolve().parents[1] / "results" / "faultdiag"


def main() -> None:
    env = environment_info()
    preds = pd.read_csv(OUT / "b4_event_predictions.csv")
    iso = preds[preds.model == "isolation_forest"]
    rows, detail = [], []
    for seed, ev in iso.groupby("seed"):
        res = nested_threshold_eval(ev)
        detail.append(res.assign(seed=seed))
        rows.append({"seed": seed, **classification_metrics(res.y, res.event_flag_nested, res.event_prob),
                     "thresholds": ", ".join(f"{a}:{t:.4f}" for a, t in
                                             res.groupby("asset_id")["threshold"].first().items())})
    table, detail = pd.DataFrame(rows), pd.concat(detail, ignore_index=True)
    detail.to_csv(OUT / "b4_if_threshold.csv", index=False, encoding="utf-8")
    L = ["# B4 follow-up: Isolation Forest threshold chosen by nested leave-one-asset-out", "",
         f"Generated by `python -m experiments.fault_threshold` at base commit {env['git_commit']}.",
         "Event score = fraction of window rows above the turbine's 99th-percentile training score (B4).",
         "For each held-out turbine, the threshold maximises F1 on the other turbines' events (ties -> higher",
         "threshold); test events never influence their own threshold. 22 events, 5 folds.", "",
         "| seed | accuracy | precision | recall | F1 | thresholds per held-out asset |", "|---|---|---|---|---|---|"]
    for _, r in table.iterrows():
        L.append(f"| {r.seed} | {r.accuracy:.3f} | {r.precision:.3f} | {r.recall:.3f} | {r.f1:.3f} | {r.thresholds} |")
    d0 = detail[detail.seed == 0].sort_values(["asset_id", "event_id"])
    L += ["", "Per event (seed 0):", "", "| event | asset | label | score | threshold | flagged |", "|---|---|---|---|---|---|"]
    for _, r in d0.iterrows():
        L.append(f"| {r.event_id} | {r.asset_id} | {'anomaly' if r.y else 'normal'} | {r.event_prob:.4f} | "
                 f"{r.threshold:.4f} | {r.event_flag_nested} |")
    (OUT / "b4_if_threshold.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L[7:7 + len(table) + 2]))


if __name__ == "__main__":
    main()
