"""C4 - Secure retrieval pipeline.

    query -> input security -> injection detection -> retriever -> document trust -> evidence filter -> LLM

1. **Input security**: the question must be non-empty, at most ``MAX_QUERY_CHARS`` characters, and free of
   control characters. Otherwise it is blocked before anything else runs.
2. **Injection detection** (C3 ``injection_detector``): a question carrying instructions for the assistant is
   blocked (policy ``block``). The model never sees it.
3. **Retriever**: production retrieval (hybrid BM25 + MiniLM, RRF, cross-encoder rerank over semantic chunks).
   It indexes the KB **store** (``documents.jsonl``, where an attacker would write), not a regenerated copy.
4. **Document trust** (C3 ``doc_trust``): every retrieved chunk is checked against the trusted registry
   (registered doc_id, registered text hash) and against content checks (provenance, stuffing, injection,
   chunk in document).
5. **Evidence filter** (C3 ``evidence_filter``): untrusted chunks are dropped before the LLM and before the
   extractive fallback. When nothing trusted remains, the answer says so and no fallback quote is produced.
6. **LLM**: GreenRAG generation (JSON with chunk citations, deterministic numeric router, guarded extractive
   fallback) over the trusted evidence only.

Trusted reference (``build_secure_retrieval``): a signed registry file ``trust_registry.json`` next to the
store, if present. It is verified with ``GREENRAG_TRUST_KEY``. A signed file without the key fails closed.
Otherwise the registry is built in process from the KB as generated by ``src.backend.kb.build``, from the
code and the datasets. Write a signed file with ``python -m src.backend.security.secure_pipeline
--write-registry``.

Every answer carries a ``SecurityReport``: what was blocked or rejected, and why.
"""

from __future__ import annotations

import argparse
import json
import re
import threading
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable

from pydantic import BaseModel, Field

from ..kb.build import KB_DIR, build_documents, load_documents
from ..kb.schema import KBDocument
from .doc_trust import (
    DocumentTrust,
    RegistryError,
    build_registry,
    calibrate_stuffing,
    env_key,
    logged_descriptions,
    save_registry,
    verify_registry,
)
from .evidence_filter import EvidenceFilter, TrustedRetriever
from .injection_detector import injection_signals, is_injection

MAX_QUERY_CHARS = 1000
EVIDENCE_K = 5
REGISTRY_FILE = "trust_registry.json"
_CONTROL = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")


# ------------------------------------------------------------------ report models

class RejectedEvidence(BaseModel):
    chunk_id: str
    doc_id: str
    reasons: list[str]


class SecurityReport(BaseModel):
    input_ok: bool = Field(description="Question passed the input checks (length, control characters).")
    input_reasons: list[str] = Field(default_factory=list)
    injection_signals: list[str] = Field(default_factory=list,
                                         description="Prompt-injection patterns found in the question.")
    blocked: bool = Field(description="The question was not answered (input check or injection detection).")
    retrieved_doc_ids: list[str] = Field(default_factory=list, description="Documents retrieved before filtering.")
    rejected: list[RejectedEvidence] = Field(default_factory=list,
                                             description="Retrieved chunks removed by trust verification.")
    passed_chunk_ids: list[str] = Field(default_factory=list, description="Trusted chunks given to the LLM.")
    registry_source: str = ""
    seconds_security: float = Field(0.0, description="Time spent in the security stages (not retrieval or LLM).")


class EvidenceRef(BaseModel):
    chunk_id: str
    doc_id: str
    rerank_score: float = Field(description="Cross-encoder relevance logit (production reranker).")
    synthetic: bool = False
    doc_type: str = ""


class SecureAnswer(BaseModel):
    question: str
    answer: str
    route: str = Field(description="blocked | no_trusted_evidence | generated | numeric | extractive_fallback")
    security: SecurityReport
    evidence: list[EvidenceRef] = Field(default_factory=list, description="Trusted evidence given to the LLM.")
    cited_chunk_ids: list[str] = Field(default_factory=list, description="Chunk ids the answer cites.")
    notes: list[str] = Field(default_factory=list)


_CITATION = re.compile(r"\[([^\[\]]*::\d+(?:\s*,\s*[^\[\]]*::\d+)*)\]")


def cited_ids(text: str) -> list[str]:
    """Chunk ids cited in square brackets (GreenRAG appends them; the fallback quotes one)."""
    return list(dict.fromkeys(c.strip() for m in _CITATION.finditer(text or "") for c in m.group(1).split(",")))


# ------------------------------------------------------------------ secure retrieval (shared with /diagnose)

@dataclass
class SecureRetrieval:
    retriever: TrustedRetriever
    chunks: list[dict]
    store_docs: list[KBDocument]
    trust: DocumentTrust
    status: dict = field(default_factory=dict)


def trusted_reference(kb_dir: Path, key: bytes | None) -> tuple[dict[str, str], str]:
    """(doc_id -> sha256, source description). A signed file needs the key; an unverifiable file fails closed."""
    path = kb_dir / REGISTRY_FILE
    if path.is_file():
        registry = json.loads(path.read_text(encoding="utf-8"))
        if registry.get("signature") and key is None:
            raise RegistryError(f"{path} is signed but GREENRAG_TRUST_KEY is not set: cannot verify, nothing trusted")
        return verify_registry(registry, key), ("signed registry file" if registry.get("signature")
                                               else "unsigned registry file (integrity not verified)")
    return build_registry(build_documents(), None)["docs"], "in-process build from code and datasets"


def build_secure_retrieval(store_docs: list[KBDocument] | None = None, kb_dir: Path = KB_DIR,
                           key: bytes | None = None, embed=None, reference: dict[str, str] | None = None
                           ) -> SecureRetrieval:
    """Production retrieval over the KB store, behind document trust and the evidence filter.

    ``store_docs`` defaults to ``documents.jsonl`` (as served). ``reference`` overrides the trusted registry
    (tests and experiments). Every store document is also scanned once at start-up; ``status`` lists the
    untrusted ones, which stay indexed but are dropped whenever they are retrieved.
    """
    from ..faultdiag.diagnosis import production_retriever
    from ..kb.chunking import semantic_chunks
    from ..kb.retrieval_eval import minilm_embed
    from ..kb.taxonomy import load_all_events

    store_path = kb_dir / "documents.jsonl"
    kb_source = "supplied" if store_docs is not None else "local"
    if store_docs is None:
        from ..settings import get_settings

        if get_settings().kb_source == "blob":
            # KB_SOURCE=blob: documents.jsonl from the Azure kb container; trust is still checked below against the
            # in-process registry, so a modified blob is rejected (fail closed)
            from ..cloud.blob import kb_documents_path

            store_path, kb_source = kb_documents_path(), "blob"
        store_docs = load_documents(store_path) if store_path.is_file() else build_documents()
    if reference is None:
        reference, source = trusted_reference(kb_dir, key if key is not None else env_key())
    else:
        source = "supplied reference"
    trust = DocumentTrust(reference, {d.doc_id: d for d in store_docs}, logged_descriptions(load_all_events()),
                          calibrate_stuffing(build_documents()))
    untrusted = {}
    for d in store_docs:
        rep = trust.check_document(d)
        if not rep.trusted:
            untrusted[d.doc_id] = rep.reasons
    embed = embed or minilm_embed()
    chunks = semantic_chunks(store_docs, embed)
    retriever = TrustedRetriever(production_retriever(store_docs, chunks, embed), EvidenceFilter(trust))
    status = {"registry_source": source, "store_documents": len(store_docs), "untrusted_in_store": untrusted,
              "kb_source": kb_source}
    return SecureRetrieval(retriever, chunks, store_docs, trust, status)


# ------------------------------------------------------------------ pipeline

def check_input(question: str) -> list[str]:
    """Reasons to refuse the raw question (empty list = acceptable)."""
    reasons = []
    if not question or not question.strip():
        reasons.append("empty question")
    if len(question) > MAX_QUERY_CHARS:
        reasons.append(f"question longer than {MAX_QUERY_CHARS} characters")
    if _CONTROL.search(question or ""):
        reasons.append("control characters in the question")
    return reasons


class _Fixed:
    """Retriever stand-in that returns already-filtered hits (so GreenRAG generation sees only those)."""

    def __init__(self, hits: list[dict]) -> None:
        self.hits = hits

    def search(self, query: str, k: int = 5) -> list[dict]:
        return self.hits[:k]


@dataclass
class SecureRAGPipeline:
    retriever: TrustedRetriever
    llm: Callable[[str], str] | None
    registry_source: str = ""
    k: int = EVIDENCE_K

    def answer(self, question: str) -> SecureAnswer:
        from ..evaluation.rag_systems import greenrag_answer

        t0 = time.perf_counter()
        input_reasons = check_input(question)
        signals = injection_signals(question) if not input_reasons else []
        blocked = bool(input_reasons) or is_injection(question)
        sec = SecurityReport(input_ok=not input_reasons, input_reasons=input_reasons, injection_signals=signals,
                             blocked=blocked, registry_source=self.registry_source)
        if blocked:
            why = "; ".join(input_reasons) if input_reasons else \
                "it contains instructions directed at the assistant (" + ", ".join(signals) + ")"
            sec.seconds_security = round(time.perf_counter() - t0, 4)
            return SecureAnswer(question=question, answer=f"The question was not processed: {why}.",
                                route="blocked", security=sec)
        t_sec = time.perf_counter() - t0
        hits = self.retriever.inner.search(question, self.k + self.retriever.overfetch)
        t1 = time.perf_counter()
        kept, rejected = self.retriever.evidence_filter.apply(hits)       # document trust + evidence filter
        kept = kept[:self.k]
        t_sec += time.perf_counter() - t1
        sec.retrieved_doc_ids = list(dict.fromkeys(h["metadata"]["doc_id"] for h in hits))
        sec.rejected = [RejectedEvidence(chunk_id=h["chunk_id"], doc_id=h["metadata"]["doc_id"],
                                         reasons=h["trust"]["reasons"]) for h in rejected]
        sec.passed_chunk_ids = [h["chunk_id"] for h in kept]
        if not kept and rejected:
            sec.seconds_security = round(t_sec, 4)
            return SecureAnswer(question=question, route="no_trusted_evidence", security=sec,
                                answer="No trusted evidence was found for this question: every retrieved "
                                       "document failed trust verification.")
        ans = greenrag_answer(self.llm or _llm_unavailable, _Fixed(kept), question)
        sec.seconds_security = round(t_sec, 4)
        evidence = [EvidenceRef(chunk_id=h["chunk_id"], doc_id=h["metadata"]["doc_id"],
                                rerank_score=float(h.get("score", 0.0)),
                                synthetic=bool(h["metadata"].get("synthetic", False)),
                                doc_type=str(h["metadata"].get("doc_type", ""))) for h in kept]
        return SecureAnswer(question=question, answer=ans.text, route=ans.route, security=sec, evidence=evidence,
                            cited_chunk_ids=cited_ids(ans.text), notes=ans.notes)


def _llm_unavailable(prompt: str) -> str:
    raise RuntimeError("no LLM configured")


@dataclass
class SecureAskService:
    """Lazily built pipeline for the API (C7) and experiments; tests inject ``pipeline``."""

    pipeline: SecureRAGPipeline | None = None
    model: str | None = None
    status: dict = field(default_factory=dict)
    retrieval_provider: Callable[[], SecureRetrieval] | None = None   # C7: shared with /diagnose and /decision

    def __post_init__(self) -> None:
        self._lock = threading.Lock()

    def _ensure(self) -> SecureRAGPipeline:
        with self._lock:
            if self.pipeline is None:
                from ..faultdiag.diagnosis import ollama_json_llm

                sec = self.retrieval_provider() if self.retrieval_provider is not None else build_secure_retrieval()
                self.status = sec.status
                self.pipeline = SecureRAGPipeline(sec.retriever, ollama_json_llm(self.model),
                                                  registry_source=sec.status["registry_source"])
            return self.pipeline

    def ask(self, question: str) -> SecureAnswer:
        return self._ensure().answer(question)


def main() -> None:
    ap = argparse.ArgumentParser(description="Trust registry for the knowledge base (C4).")
    ap.add_argument("--write-registry", action="store_true",
                    help=f"write {REGISTRY_FILE} from the KB build, signed with GREENRAG_TRUST_KEY")
    args = ap.parse_args()
    if args.write_registry:
        key = env_key()
        if key is None:
            raise SystemExit("GREENRAG_TRUST_KEY is not set: refusing to write an unsigned registry")
        path = KB_DIR / REGISTRY_FILE
        save_registry(build_registry(build_documents(), key), path)
        print(f"wrote signed registry for {len(build_documents())} documents to {path}")


if __name__ == "__main__":
    main()
