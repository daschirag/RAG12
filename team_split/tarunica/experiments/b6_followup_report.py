"""B6 follow-up: re-score saved judgements with deterministic verification of template statements (no LLM calls).

    python -m experiments.b6_followup_report

Judge v2 (prompt fix) failed its calibration on true process statements (34% recognised), so it is not used.
Instead, statements that GreenRAG's fallback writes from templates are verified by code against the retrieved
evidence (rag_eval.verify_template_claim); every other claim keeps its original judge (v1) verdict.
Systems: GreenRAG run 2, hybrid RAG run 1 (no expansion), hybrid RAG + expansion. Fault items only.
Output: results/rag/run2/b6_followup_deterministic.md and .csv.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from experiments.rag_evaluation import OUT, RUN2, build_items, load_jsonl, per_answer_table
from src.backend.evaluation.provenance import environment_info
from src.backend.evaluation.rag_eval import verify_template_claim
from src.backend.forecasting.evaluation import paired_day_bootstrap
from src.backend.kb.build import build_documents
from src.backend.kb.retrieval_eval import bootstrap_mean_ci
from src.backend.kb.taxonomy import COMPONENTS

SETS = {  # name: (answers file, v1 judgements file, system)
    "greenrag_run2": (RUN2 / "answers.jsonl", RUN2 / "judgements.jsonl", "greenrag"),
    "hybrid_run1": (OUT / "answers.jsonl", OUT / "judgements.jsonl", "hybrid_rag"),
    "hybrid_expanded": (RUN2 / "hybrid_expanded_answers.jsonl", RUN2 / "judgements_v1_hybrid_expanded.jsonl",
                        "hybrid_rag"),
}


def main() -> None:
    env = environment_info()
    docs = build_documents()
    components = {d.doc_id: d.component for d in docs}
    labels = {c.key: c.label for c in COMPONENTS}
    items = [it for it in build_items(docs) if it["dataset"] != "kb"]
    by_item = {it["item_id"]: it for it in items}
    tables, overrides = {}, []
    for name, (ans_path, jud_path, system) in SETS.items():
        answers = [a for a in load_jsonl(ans_path) if a["system"] == system and a["item_id"] in by_item]
        ans = {a["item_id"]: a for a in answers}
        judged = [j for j in load_jsonl(jud_path) if j["system"] == system and j["item_id"] in by_item]
        corrected = []
        for j in judged:
            a, q = ans[j["item_id"]], by_item[j["item_id"]]["question"]
            claims = []
            for c in j["claims"]:
                v = verify_template_claim(c["claim"], q, a["context"], components, labels)
                if v is not None:
                    overrides.append({"set": name, "item_id": j["item_id"], "claim": c["claim"], "code_verdict": v,
                                      "judge_v1_verdict": c["supported_by_reference"]})
                    c = {**c, "supported_by_context": v, "supported_by_reference": v}
                claims.append(c)
            corrected.append({**j, "claims": claims})
        tables[(name, "v1")] = per_answer_table(items, answers, judged, docs)
        tables[(name, "v1+code")] = per_answer_table(items, answers, corrected, docs)
    ov = pd.DataFrame(overrides)
    ov.to_csv(RUN2 / "b6_followup_template_claims.csv", index=False, encoding="utf-8")

    L = ["# B6 follow-up: template statements verified by code (judge v1 for everything else)", "",
         f"Generated by `python -m experiments.b6_followup_report` at base commit {env['git_commit']}.",
         "No answers regenerated and no LLM calls: saved v1 judgements, with GreenRAG's template statements",
         "(retrieval/input statements filled in by code) checked deterministically against the retrieved evidence.",
         "Mean [95% bootstrap CI]; paired differences resample events.", ""]
    for ds in ("fault_logged", "fault_unlogged"):
        L += [f"## {ds}", "", "| system | scoring | faithfulness | hallucination rate | claim unsupported | answer relevance |",
              "|---|---|---|---|---|---|"]
        for name in SETS:
            for sc in ("v1", "v1+code"):
                s = tables[(name, sc)]
                s = s[s.dataset == ds]
                cells = []
                for m in ("faithfulness", "hallucinated", "claim_unsupported_rate", "answer_relevance"):
                    v = s[m].dropna()
                    cells.append("n/a" if v.empty else "{:.3f} [{:.3f}, {:.3f}]".format(*bootstrap_mean_ci(v)))
                L.append(f"| {name} | {sc} | " + " | ".join(cells) + " |")
        g = tables[("greenrag_run2", "v1+code")]
        h = tables[("hybrid_expanded", "v1+code")]
        g, h = g[g.dataset == ds].set_index("item_id"), h[h.dataset == ds].set_index("item_id")
        for m, better in (("faithfulness", "higher"), ("hallucinated", "lower")):
            # paired_day_bootstrap reports A - B; for these metrics sign conventions are stated explicitly.
            r = paired_day_bootstrap(g[m].dropna(), h[m].dropna(), n_resamples=10_000, seed=0)
            L.append(f"\nGreenRAG run 2 - hybrid RAG + expansion ({m}, {better} is better; v1+code): "
                     f"{r.mean_diff:+.3f}, 95% CI [{r.ci_low:+.3f}, {r.ci_high:+.3f}], {r.n_days} events")
        L.append("")
    gr = ov[ov.set == "greenrag_run2"] if not ov.empty else ov
    flipped_true = int(((gr.code_verdict == True) & (gr.judge_v1_verdict == False)).sum()) if not gr.empty else 0  # noqa: E712
    flipped_false = int(((gr.code_verdict == False) & (gr.judge_v1_verdict == True)).sum()) if not gr.empty else 0  # noqa: E712
    L += ["## GreenRAG run 2: template statements", "",
          f"Template statements in GreenRAG run-2 answers: {len(gr)} (code says true: {int(gr.code_verdict.sum())}, "
          f"false: {int((~gr.code_verdict.astype(bool)).sum())}). The judge (v1) had called {flipped_true} true ones "
          f"unsupported and {flipped_false} false ones supported.", ""]
    for ds in ("fault_logged", "fault_unlogged"):
        a, b = tables[("greenrag_run2", "v1")], tables[("greenrag_run2", "v1+code")]
        L.append(f"- {ds}: hallucination rate {a[a.dataset == ds].hallucinated.mean():.3f} (v1) -> "
                 f"{b[b.dataset == ds].hallucinated.mean():.3f} (template statements verified by code)")
    (RUN2 / "b6_followup_deterministic.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
