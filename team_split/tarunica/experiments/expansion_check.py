"""B6 fix check: does sibling-chunk expansion regress general retrieval on the 64 labelled KB queries?

    python -m experiments.expansion_check

Variants, all on B3's production retriever (hybrid BM25 + MiniLM, RRF, cross-encoder rerank, semantic chunks):
- A  baseline: top 5 reranked chunks (B3).
- B  production expansion: the same top 5 chunks plus each one's adjacent sibling chunks (no cap).
- C  budget expansion: siblings inserted after their hit, total capped at 5 chunks (can push documents out).

Metrics: B3's Precision@5 / Recall@5 / MRR / nDCG@5 on the chunk list (first 5 chunks), and the same metrics on
the ranked list of distinct documents in the whole context (for B this is the full expanded context). Also the
share of event/symptom/maintenance queries whose context contains the relevant fault record's cause text.
Output: results/kb/b6_expansion_check.md and .csv.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from src.backend.evaluation.provenance import environment_info
from src.backend.kb.build import build_documents
from src.backend.kb.chunking import semantic_chunks
from src.backend.kb.queries import build_queries
from src.backend.kb.retrieval_eval import CosineIndex, bootstrap_mean_ci, metrics_at_k, minilm_embed
from src.backend.retrieval.hybrid_retriever import (
    BM25Index,
    HybridRetriever,
    RerankRetriever,
    SiblingExpander,
    cross_encoder_scorer,
)

OUT = Path(__file__).resolve().parents[1] / "results" / "kb"
METRICS = ("precision_at_k", "recall_at_k", "mrr", "ndcg_at_k")


def distinct_docs(hits) -> list[str]:
    return list(dict.fromkeys(h["metadata"]["doc_id"] for h in hits))


def main() -> None:
    env = environment_info()
    docs = build_documents()
    queries = build_queries(docs)
    embed = minilm_embed()
    chunks = semantic_chunks(docs, embed)
    hybrid = HybridRetriever([BM25Index(chunks), CosineIndex(chunks, embed)], k_rrf=60, candidates=50)
    rerank = RerankRetriever(hybrid, cross_encoder_scorer(), candidates=20)
    expanders = {"A_baseline": None, "B_expansion": SiblingExpander(chunks), "C_expansion_budget5": SiblingExpander(chunks, budget=5)}
    rows = []
    for q in queries:
        top5 = rerank.search(q.text, 5)
        for name, exp in expanders.items():
            ctx = exp.expand(top5) if exp is not None else top5
            chunk_m = metrics_at_k([h["metadata"]["doc_id"] for h in ctx], q.relevant, 5)
            doc_m = metrics_at_k(distinct_docs(ctx), q.relevant, 5)
            fault_rel = [d for d in q.relevant if d.startswith("fault-")]
            cause_in_ctx = (any("original wording" in h["text"] for h in ctx if h["metadata"]["doc_id"] in fault_rel)
                            if fault_rel else None)
            rows.append({"query_id": q.query_id, "query_type": q.query_type, "variant": name,
                         "context_chunks": len(ctx), "context_chars": sum(len(h["text"]) for h in ctx),
                         **{f"chunk_{k}": v for k, v in chunk_m.items()}, **{f"doc_{k}": v for k, v in doc_m.items()},
                         "fault_cause_in_context": cause_in_ctx})
    t = pd.DataFrame(rows)
    t.to_csv(OUT / "b6_expansion_check.csv", index=False, encoding="utf-8")
    L = ["# Sibling-chunk expansion: retrieval regression check (64 labelled KB queries)", "",
         f"Generated by `python -m experiments.expansion_check` at base commit {env['git_commit']}.",
         "Retriever: B3 production (hybrid + rerank, semantic chunks). Mean over queries [95% bootstrap CI].", "",
         "## B3 metrics on the first 5 chunks of the context", "",
         "| variant | Precision@5 | Recall@5 | MRR | nDCG@5 |", "|---|---|---|---|---|"]
    for name in expanders:
        s = t[t.variant == name]
        L.append(f"| {name} | " + " | ".join(
            "{:.3f} [{:.3f}, {:.3f}]".format(*bootstrap_mean_ci(s[f"chunk_{m}"])) for m in METRICS) + " |")
    L += ["", "## Same metrics on the distinct documents of the whole context", "",
          "| variant | Precision@5 | Recall@5 | MRR | nDCG@5 | mean chunks | mean chars |", "|---|---|---|---|---|---|---|"]
    for name in expanders:
        s = t[t.variant == name]
        L.append(f"| {name} | " + " | ".join(f"{s[f'doc_{m}'].mean():.3f}" for m in METRICS)
                 + f" | {s.context_chunks.mean():.2f} | {s.context_chars.mean():.0f} |")
    f = t[t.fault_cause_in_context.notna()]
    L += ["", f"## Fault record cause text in the context ({f.query_id.nunique()} queries with a relevant fault record)", "",
          "| variant | queries whose context contains the relevant record's logged cause |", "|---|---|"]
    for name in expanders:
        s = f[f.variant == name]
        L.append(f"| {name} | {int(s.fault_cause_in_context.sum())}/{len(s)} |")
    (OUT / "b6_expansion_check.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L[5:]))


if __name__ == "__main__":
    main()
