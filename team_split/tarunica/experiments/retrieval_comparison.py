"""B3: compare keyword (BM25), vector, hybrid (RRF) and hybrid + cross-encoder reranking.

    python -m experiments.retrieval_comparison

Same chunks for every variant: B2's semantic chunks of the B1 knowledge base.
Same labelled queries (64) and document-level metrics as B2, top 5. Also
evaluates the query classifier and a classifier-routed retriever whose rule
was fixed before running: quantitative -> BM25, conceptual -> hybrid + rerank.

Outputs (results/kb/): b3_retrieval_summary.md, b3_retrieval_metrics.csv (per query
and variant), b3_paired_bootstrap.csv, b3_classifier.csv, b3_run.json.
"""

from __future__ import annotations

import itertools
import json
import time
from pathlib import Path

import numpy as np
import pandas as pd

from src.backend.evaluation.provenance import environment_info
from src.backend.forecasting.evaluation import paired_day_bootstrap
from src.backend.kb.build import build_documents
from src.backend.kb.chunking import semantic_chunks
from src.backend.kb.queries import build_queries
from src.backend.kb.retrieval_eval import K, CosineIndex, bootstrap_mean_ci, evaluate, minilm_embed
from src.backend.retrieval.hybrid_retriever import (
    BM25Index,
    HybridRetriever,
    RerankRetriever,
    RoutedRetriever,
    cross_encoder_scorer,
)
from src.backend.retrieval.query_classifier import classify_intent

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results" / "kb"
METRICS = ("precision_at_k", "recall_at_k", "mrr", "ndcg_at_k")
RERANK_MODEL = "cross-encoder/ms-marco-MiniLM-L-6-v2"


def timed_evaluate(retriever, queries) -> tuple[pd.DataFrame, float]:
    for q in queries[:3]:
        retriever.search(q.text, K)                       # warm-up (model load, caches)
    start = time.perf_counter()
    res = evaluate(retriever, queries, K)
    return res, 1000 * (time.perf_counter() - start) / len(queries)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    env = environment_info()
    docs = build_documents()
    queries = build_queries(docs)
    embed = minilm_embed()
    chunks = semantic_chunks(docs, embed)
    bm25 = BM25Index(chunks)
    vector = CosineIndex(chunks, embed)
    hybrid = HybridRetriever([bm25, vector], k_rrf=60, candidates=50)
    rerank = RerankRetriever(hybrid, cross_encoder_scorer(RERANK_MODEL), candidates=20)
    routed = RoutedRetriever(classify_intent, {"quantitative": bm25, "conceptual": rerank})
    variants = {"bm25": bm25, "vector": vector, "hybrid_rrf": hybrid, "hybrid_rerank": rerank,
                "routed": routed}

    per_query, latency = [], {}
    for name, retriever in variants.items():
        res, ms = timed_evaluate(retriever, queries)
        per_query.append(res.assign(variant=name))
        latency[name] = ms
        print(f"{name:<14} " + "  ".join(f"{m} {res[m].mean():.3f}" for m in METRICS) + f"  {ms:.1f} ms/query")
    per_query = pd.concat(per_query, ignore_index=True)
    per_query.to_csv(OUT / "b3_retrieval_metrics.csv", index=False, encoding="utf-8")

    clf = pd.DataFrame([{"query_id": q.query_id, "label": q.query_class, "predicted": classify_intent(q.text)}
                        for q in queries])
    clf.to_csv(OUT / "b3_classifier.csv", index=False, encoding="utf-8")
    confusion = pd.crosstab(clf.label, clf.predicted)

    boots = []
    order = list(variants)
    for a, b in itertools.combinations(order, 2):
        sa = per_query[per_query.variant == a].set_index("query_id")["ndcg_at_k"]
        sb = per_query[per_query.variant == b].set_index("query_id")["ndcg_at_k"]
        r = paired_day_bootstrap(sa, sb, n_resamples=10_000, seed=0)
        boots.append({"a": a, "b": b, "metric": "ndcg_at_k", **r.as_dict()})
    boots = pd.DataFrame(boots)
    boots.to_csv(OUT / "b3_paired_bootstrap.csv", index=False, encoding="utf-8")

    L = ["# B3 retrieval comparison", "",
         f"Generated by `python -m experiments.retrieval_comparison` at base commit {env['git_commit']}.",
         f"{len(chunks)} semantic chunks (B2) of {len(docs)} KB documents; {len(queries)} labelled queries; top {K}.",
         f"Vector: all-MiniLM-L6-v2 exact cosine. Hybrid: reciprocal rank fusion (k=60) of BM25 and vector top 50.",
         f"Rerank: {RERANK_MODEL} over the hybrid top 20. Routed: quantitative -> BM25, conceptual -> hybrid_rerank",
         "(rule fixed before the run). Mean over queries with 95% bootstrap CI (queries resampled, seed 0).",
         "Latency: mean wall-clock per query on CPU after warm-up (includes query embedding / cross-encoder).", "",
         "| variant | Precision@5 | Recall@5 | MRR | nDCG@5 | ms/query |", "|---|---|---|---|---|---|"]
    for name in order:
        r = per_query[per_query.variant == name]
        cells = []
        for m in METRICS:
            mean, lo, hi = bootstrap_mean_ci(r[m])
            cells.append(f"{mean:.3f} [{lo:.3f}, {hi:.3f}]")
        L.append(f"| {name} | " + " | ".join(cells) + f" | {latency[name]:.1f} |")
    L += ["", "## nDCG@5 by query type", "", "| query type | n | " + " | ".join(order) + " |",
          "|---|---|" + "---|" * len(order)]
    piv = per_query.pivot_table(index="query_type", columns="variant", values="ndcg_at_k", aggfunc="mean")
    n = per_query[per_query.variant == "bm25"].groupby("query_type").size()
    for qt, row in piv.iterrows():
        L.append(f"| {qt} | {n[qt]} | " + " | ".join(f"{row[v]:.3f}" for v in order) + " |")
    L += ["", "## nDCG@5 by query class (classifier labels by construction)", "",
          "| class | n | " + " | ".join(order) + " |", "|---|---|" + "---|" * len(order)]
    pc = per_query.pivot_table(index="query_class", columns="variant", values="ndcg_at_k", aggfunc="mean")
    nc = per_query[per_query.variant == "bm25"].groupby("query_class").size()
    for qc, row in pc.iterrows():
        L.append(f"| {qc} | {nc[qc]} | " + " | ".join(f"{row[v]:.3f}" for v in order) + " |")
    L += ["", "## Paired bootstrap, nDCG@5 (A - B; positive = A better)", "",
          "| A | B | mean diff | 95% CI | share of resamples with A < B |", "|---|---|---|---|---|"]
    for _, r in boots.iterrows():
        L.append(f"| {r.a} | {r.b} | {r.mean_diff:+.3f} | [{r.ci_low:+.3f}, {r.ci_high:+.3f}] | {r.share_a_better:.3f} |")
    acc = float((clf.label == clf.predicted).mean())
    L += ["", "## Query classifier (rule-based, src/backend/retrieval/query_classifier.py)", "",
          f"Accuracy on the 64 labelled queries: {acc:.3f}. Confusion (rows = label, columns = predicted):", "",
          "| label \\ predicted | " + " | ".join(confusion.columns) + " |", "|---|" + "---|" * len(confusion.columns)]
    for label, row in confusion.iterrows():
        L.append(f"| {label} | " + " | ".join(str(int(v)) for v in row) + " |")
    L += ["", "Caveat: the rules were written with the query templates in view and the set has only 6 quantitative",
          "queries, so this accuracy is optimistic. tests/test_hybrid_retrieval.py adds independent examples."]
    (OUT / "b3_retrieval_summary.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    (OUT / "b3_run.json").write_text(json.dumps({"environment": env, "k": K, "chunks": len(chunks),
                                                 "latency_ms": latency, "rerank_model": RERANK_MODEL,
                                                 "classifier_accuracy": acc}, indent=2), encoding="utf-8")
    print(f"classifier accuracy {acc:.3f}")


if __name__ == "__main__":
    main()
