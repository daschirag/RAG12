"""B5: diagnose all Wind Farm A events with the fault-to-RAG pipeline (production retrieval + local LLM).

    python -m experiments.fault_rag

Two modes per event:
- logged:   the event's own logbook-derived documents may be retrieved (historical case);
- unlogged: the event's own fault and maintenance documents are excluded, simulating
            a new anomaly with no log entry yet (the honest test of evidence-derived causes).
Needs Ollama (`ollama serve`); if it is down, reports fall back to evidence-only text
and this is recorded per report.

Outputs (results/faultdiag/): b5_reports.jsonl (every validated report), b5_summary.md, b5_run.json.
"""

from __future__ import annotations

import json
import time
from pathlib import Path

import pandas as pd

from src.backend.evaluation.provenance import environment_info
from src.backend.faultdiag.diagnosis import (
    Diagnoser,
    event_windows,
    load_reliability,
    load_signals,
    ollama_json_llm,
    production_retriever,
)
from src.backend.kb.build import build_documents
from src.backend.kb.taxonomy import categorize, load_events

OUT = Path(__file__).resolve().parents[1] / "results" / "faultdiag"


def main() -> None:
    env = environment_info()
    docs = build_documents()
    components = {d.doc_id: d.component for d in docs}
    events = load_events("A")
    truth = {int(e.event_id): (e.event_label, categorize(e.event_description)[0]) for e in events.itertuples()}
    reliability = load_reliability()
    diagnoser = Diagnoser(production_retriever(docs), ollama_json_llm(), reliability, event_windows(events))
    rows, start = [], time.perf_counter()
    with (OUT / "b5_reports.jsonl").open("w", encoding="utf-8") as fh:
        for signal in load_signals():
            for mode in ("logged", "unlogged"):
                t = time.perf_counter()
                report = diagnoser.diagnose(signal, components, exclude_own_event=(mode == "unlogged"))
                fh.write(json.dumps({"mode": mode, **report.model_dump(mode="json")}, ensure_ascii=False) + "\n")
                label, comp = truth[signal.event_id]
                own_retrieved = any(e.event_id == signal.event_id and e.farm == "A" for e in report.evidence)
                rows.append({"event_id": signal.event_id, "asset_id": signal.asset_id, "label": label,
                             "mode": mode, "true_component": comp, "anomaly_score": signal.anomaly_score,
                             "evidence_support": report.confidence.evidence_support,
                             "confidence": report.confidence.level, "generation": report.generation,
                             "evidence_component": report.likely_cause_component,
                             "component_correct": (report.likely_cause_component == comp) if label == "anomaly" else None,
                             "own_event_retrieved": own_retrieved, "severity": report.severity,
                             "n_evidence": len(report.evidence), "seconds": round(time.perf_counter() - t, 1)})
                print(f"event {signal.event_id:>3} {mode:<8} {report.generation:<8} support "
                      f"{report.confidence.evidence_support:<6} conf {report.confidence.level:<8} "
                      f"component {report.likely_cause_component} (true {comp})")
    t = pd.DataFrame(rows)
    t.to_csv(OUT / "b5_results.csv", index=False, encoding="utf-8")

    L = ["# B5 fault diagnosis -> RAG, Wind Farm A", "",
         f"Generated by `python -m experiments.fault_rag` at base commit {env['git_commit']}.",
         "Retrieval: GreenRAG production (hybrid BM25 + MiniLM, RRF, cross-encoder rerank), top 5 evidence chunks.",
         f"LLM: Ollama JSON mode (temperature 0, seed 0). Detector reliability: {reliability.detector} event AUC "
         f"{reliability.value:.3f}, 95% CI [{reliability.ci95_low:.3f}, {reliability.ci95_high:.3f}], "
         f"{reliability.n_events} events.", "",
         "Every report passed pydantic validation (cited chunk ids are a subset of the retrieved evidence; weak or no",
         "evidence forces low confidence).", "",
         "| mode | label | events | LLM reports | fallback | support strong/weak/none | confidence low/moderate/high | "
         "own event retrieved | evidence component correct (anomaly) | severity high/medium/low/undetermined |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for (mode, label), g in t.groupby(["mode", "label"]):
        sup = "/".join(str(int((g.evidence_support == s).sum())) for s in ("strong", "weak", "none"))
        conf = "/".join(str(int((g.confidence == c).sum())) for c in ("low", "moderate", "high"))
        sev = "/".join(str(int((g.severity == s).sum())) for s in ("high", "medium", "low", "undetermined"))
        comp = (f"{int(g.component_correct.sum())}/{len(g)}" if label == "anomaly" else "n/a")
        L.append(f"| {mode} | {label} | {len(g)} | {int((g.generation == 'llm').sum())} | "
                 f"{int((g.generation == 'fallback').sum())} | {sup} | {conf} | {int(g.own_event_retrieved.sum())} | "
                 f"{comp} | {sev} |")
    L += ["", "Per anomaly event:", "",
          "| event | asset | true component | logged: evidence component | unlogged: evidence component | "
          "unlogged support |", "|---|---|---|---|---|---|"]
    a = t[t.label == "anomaly"].pivot_table(index=["event_id", "asset_id", "true_component"], columns="mode",
                                           values=["evidence_component", "evidence_support"], aggfunc="first")
    for (eid, asset, comp), r in a.iterrows():
        L.append(f"| {eid} | {asset} | {comp} | {r[('evidence_component', 'logged')]} | "
                 f"{r[('evidence_component', 'unlogged')]} | {r[('evidence_support', 'unlogged')]} |")
    L += ["", f"Mean time per report: {t.seconds.mean():.1f} s (retrieval + LLM on this machine)."]
    (OUT / "b5_summary.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    (OUT / "b5_run.json").write_text(json.dumps({"environment": env, "reliability": reliability.model_dump(),
                                                 "total_seconds": round(time.perf_counter() - start, 1)}, indent=2),
                                     encoding="utf-8")


if __name__ == "__main__":
    main()
