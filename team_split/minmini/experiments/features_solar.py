"""A2: build 1-hour-ahead features for both plants and describe them.

    python -m experiments.features_solar

Outputs results/forecasting/features_summary.md and features_plant{1,2}.json:
split sizes and date ranges, missing values per feature, and each feature's
Spearman correlation with the target on *training daytime rows only*.
"""

from __future__ import annotations

import json
from pathlib import Path

from src.backend.evaluation.provenance import environment_info
from src.backend.forecasting.features import (
    FEATURE_DESCRIPTIONS,
    FeatureConfig,
    build_features,
    split_by_target_day,
)
from src.backend.forecasting.preprocess import preprocess_plant

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results" / "forecasting"


def describe_plant(plant: int, cfg: FeatureConfig) -> dict:
    frame = preprocess_plant(plant).frame
    data = build_features(frame, cfg)
    parts = split_by_target_day(data)
    splits = {
        name: {
            "rows": len(p.y),
            "daytime_rows": int(p.meta["target_daytime"].sum()),
            "first_target": str(p.meta["target_time"].min()),
            "last_target": str(p.meta["target_time"].max()),
        }
        for name, p in parts.items()
    }
    train = parts["train"]
    day = train.meta["target_daytime"]
    X_day, y_day = train.X[day], train.y[day]
    features = {
        name: {
            "missing_train": int(train.X[name].isna().sum()),
            "spearman_train_daytime": round(float(X_day[name].corr(y_day, method="spearman")), 4),
        }
        for name in data.feature_names
    }
    return {
        "plant": plant,
        "rows_total": len(data.y),
        "hourly_equivalent_rows": len(data.y) // 4,
        "splits": splits,
        "features": features,
    }


def main() -> None:
    RESULTS.mkdir(parents=True, exist_ok=True)
    cfg = FeatureConfig()
    env = environment_info()
    results = {}
    for plant in (1, 2):
        res = describe_plant(plant, cfg)
        results[plant] = res
        payload = {"summary": res, "config": {k: getattr(cfg, k) for k in cfg.__dataclass_fields__},
                   "environment": env}
        (RESULTS / f"features_plant{plant}.json").write_text(json.dumps(payload, indent=2), encoding="utf-8")
        s = res["splits"]
        print(f"plant {plant}: rows={res['rows_total']} " +
              " ".join(f"{k}={v['rows']}" for k, v in s.items()))

    lines = [
        "# A2 feature engineering summary",
        "",
        f"Generated by `python -m experiments.features_solar` at commit {env['git_commit']}.",
        "Resolution: native 15 min (no resampling). Horizon: 1 hour ahead (4 steps) for every model.",
        "Split by the day of the target time: train 21 days, val 4, calib 4 (reserved for A4 conformal",
        "calibration), test = remaining 5 days. Rows with a missing target are dropped.",
        "",
        "## Split sizes",
        "",
        "| plant | split | rows | daytime rows | first target | last target |",
        "|---|---|---|---|---|---|",
    ]
    for plant, res in results.items():
        for name, sp in res["splits"].items():
            lines.append(f"| {plant} | {name} | {sp['rows']} | {sp['daytime_rows']} | "
                         f"{sp['first_target']} | {sp['last_target']} |")
    lines += [
        "",
        "## Features (train split only; Spearman on daytime targets)",
        "",
        "| feature | description | P1 missing | P1 spearman | P2 missing | P2 spearman |",
        "|---|---|---|---|---|---|",
    ]
    for name, desc in FEATURE_DESCRIPTIONS.items():
        f1, f2 = results[1]["features"][name], results[2]["features"][name]
        lines.append(f"| {name} | {desc} | {f1['missing_train']} | {f1['spearman_train_daytime']} | "
                     f"{f2['missing_train']} | {f2['spearman_train_daytime']} |")
    lines += [
        "",
        "Correlations are descriptive only (no feature selection is done on them). `month` takes only the",
        "values 5 and 6 and `day` acts as a trend proxy over a 34-day record, so both can extrapolate",
        "poorly to the test days; they are kept because the plan asks for them and A3 will report results.",
    ]
    (RESULTS / "features_summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
