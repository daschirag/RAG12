"""A1: run solar preprocessing for both plants and save reports.

    python -m experiments.preprocess_solar

Outputs:
- results/forecasting/preprocessing_report_plant{1,2}.json (counts, config, environment)
- results/forecasting/preprocessing_summary.md
- results/forecasting/preprocessing_plant{1,2}.png (grayscale)
- data/processed/forecasting/solar_plant{1,2}_15min.csv (gitignored)
"""

from __future__ import annotations

import json
from dataclasses import asdict
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.dates as mdates  # noqa: E402
import matplotlib.pyplot as plt  # noqa: E402

from src.backend.evaluation.provenance import environment_info  # noqa: E402
from src.backend.forecasting.preprocess import (  # noqa: E402
    TARGET,
    PreprocessConfig,
    PreprocessResult,
    preprocess_plant,
)

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results" / "forecasting"
PROCESSED = ROOT / "data" / "processed" / "forecasting"


def _config_dict(cfg: PreprocessConfig) -> dict:
    return {k: str(v) if not isinstance(v, (int, float, tuple)) else v for k, v in asdict(cfg).items()}


def _plot(result: PreprocessResult, plant: int, path: Path) -> None:
    f = result.frame
    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(11, 5.5), sharex=True)
    ax1.plot(f.index, f[TARGET], color="black", linewidth=0.5, label="plant AC power (kW)")
    outl = f[f["flag_stat_outlier"]]
    ax1.scatter(outl.index, outl[TARGET], s=10, facecolors="none", edgecolors="black",
                label=f"statistical outlier flag (n={len(outl)})")
    missing = f[f[TARGET].isna()]
    ax1.scatter(missing.index, [0] * len(missing), marker="|", color="0.5", s=40,
                label=f"target missing (n={len(missing)})")
    ax1.set_ylabel("AC power (kW)")
    ax1.legend(loc="upper left", fontsize=7, frameon=False)
    ax1.set_title(f"Plant {plant}: cleaned 15-min series (A1)", fontsize=10)
    ax2.plot(f.index, f["inverter_coverage"], color="0.35", linewidth=0.7)
    ax2.set_ylabel("inverter coverage")
    ax2.set_ylim(-0.05, 1.05)
    ax2.xaxis.set_major_locator(mdates.DayLocator(interval=4))
    ax2.xaxis.set_major_formatter(mdates.DateFormatter("%Y-%m-%d"))
    fig.tight_layout()
    fig.savefig(path, dpi=130)
    plt.close(fig)


def main() -> None:
    RESULTS.mkdir(parents=True, exist_ok=True)
    PROCESSED.mkdir(parents=True, exist_ok=True)
    cfg = PreprocessConfig()
    env = environment_info()
    rows = []
    for plant in (1, 2):
        result = preprocess_plant(plant, cfg)
        rep = result.report
        payload = {"report": rep.to_dict(), "config": _config_dict(cfg), "environment": env}
        (RESULTS / f"preprocessing_report_plant{plant}.json").write_text(
            json.dumps(payload, indent=2), encoding="utf-8"
        )
        result.frame.to_csv(PROCESSED / f"solar_plant{plant}_15min.csv", encoding="utf-8")
        _plot(result, plant, RESULTS / f"preprocessing_plant{plant}.png")
        f = result.frame
        day = f[f["irradiation"] > cfg.daytime_irradiation]
        rows.append({
            "plant": plant,
            "slots": rep.grid_slots,
            "no_generation": rep.slots_without_generation,
            "no_weather": rep.slots_without_weather,
            "partial_coverage": rep.slots_partial_coverage,
            "night_filled": rep.target_night_filled,
            "night_inconsistent": rep.night_inconsistent,
            "bound_violations": sum(rep.bound_violations.values()),
            "weather_ffilled": sum(rep.weather_ffilled.values()),
            "target_missing": rep.target_missing_final,
            "stat_outliers": rep.stat_outliers_flagged,
            "dc_ac_ratio": rep.dc_ac_ratio_median,
            "day_corr": round(float(day[TARGET].corr(day["irradiation"])), 4),
        })
        print(f"plant {plant}: slots={rep.grid_slots} target_missing={rep.target_missing_final} "
              f"stat_outliers={rep.stat_outliers_flagged} dc_ac_ratio={rep.dc_ac_ratio_median}")

    header = list(rows[0])
    lines = [
        "# A1 solar preprocessing summary",
        "",
        f"Generated by `python -m experiments.preprocess_solar` at commit {env['git_commit']}.",
        "Counts are 15-min slots. `day_corr` = Pearson correlation of cleaned plant AC power",
        "with irradiation over daytime slots (irradiation > 0.1).",
        "",
        "| " + " | ".join(header) + " |",
        "|" + "---|" * len(header),
    ]
    lines += ["| " + " | ".join(str(r[h]) for h in header) + " |" for r in rows]
    (RESULTS / "preprocessing_summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
